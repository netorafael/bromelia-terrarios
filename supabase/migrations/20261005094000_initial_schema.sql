create or replace function public.finalize_sale(
  p_store_id uuid, p_payment_method public.payment_method,
  p_discount_percent numeric, p_items jsonb
) returns uuid language plpgsql security definer set search_path = public as $$
declare
  current_user_id uuid := auth.uid();
  sale_id uuid;
  item jsonb;
  product_row record;
  subtotal numeric(12,2) := 0;
  discount_amount numeric(12,2);
  sale_total numeric(12,2);
  before_quantity integer;
  requested_quantity integer;
begin
  if current_user_id is null or not public.is_store_member(p_store_id) then
    raise exception 'Usuário não autorizado para esta loja';
  end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'A venda precisa ter itens'; end if;
  for item in select * from jsonb_array_elements(p_items) loop
    requested_quantity := (item->>'quantity')::integer;
    if requested_quantity <= 0 then raise exception 'Quantidade inválida'; end if;
    select p.*, coalesce(il.quantity, 0) as available_quantity
      into product_row from public.products p
      left join public.inventory_levels il on il.product_id = p.id
      where p.id = (item->>'product_id')::uuid and p.store_id = p_store_id and p.active and p.sellable
      for update;
    if not found then raise exception 'Produto não encontrado'; end if;
    if product_row.available_quantity < requested_quantity then raise exception 'Estoque insuficiente para %', product_row.name; end if;
    subtotal := subtotal + (product_row.sale_price * requested_quantity);
  end loop;
  if p_discount_percent < 0 or p_discount_percent > 100 then raise exception 'Desconto inválido'; end if;
  discount_amount := round(subtotal * p_discount_percent / 100, 2);
  sale_total := subtotal - discount_amount;
  insert into public.sales (store_id, status, subtotal, discount_percent, discount_amount, total, created_by, paid_at)
  values (p_store_id, 'paid', subtotal, p_discount_percent, discount_amount, sale_total, current_user_id, now())
  returning id into sale_id;
  for item in select * from jsonb_array_elements(p_items) loop
    requested_quantity := (item->>'quantity')::integer;
    select p.*, il.quantity into product_row from public.products p
      join public.inventory_levels il on il.product_id = p.id
      where p.id = (item->>'product_id')::uuid and p.store_id = p_store_id for update;
    before_quantity := product_row.quantity;
    insert into public.sale_items (sale_id, product_id, product_name_snapshot, sku_snapshot, unit_price, unit_cost_snapshot, quantity, line_total)
    values (sale_id, product_row.id, product_row.name, product_row.sku, product_row.sale_price, product_row.cost_price, requested_quantity, product_row.sale_price * requested_quantity);
    update public.inventory_levels set quantity = quantity - requested_quantity, updated_at = now() where product_id = product_row.id;
    insert into public.stock_movements (store_id, product_id, type, quantity_delta, quantity_before, quantity_after, sale_id, created_by)
    values (p_store_id, product_row.id, 'sale', -requested_quantity, before_quantity, before_quantity - requested_quantity, sale_id, current_user_id);
  end loop;
  insert into public.payments (sale_id, method, amount, status, paid_at)
  values (sale_id, p_payment_method, sale_total, 'approved', now());
  return sale_id;
end $$;
revoke all on function public.finalize_sale(uuid, public.payment_method, numeric, jsonb) from public;
grant execute on function public.finalize_sale(uuid, public.payment_method, numeric, jsonb) to authenticated;

create or replace function public.ensure_current_user_setup() returns uuid
language plpgsql security definer set search_path = public as $$
declare store_id uuid; user_email text;
begin
  if auth.uid() is null then raise exception 'Usuário não autenticado'; end if;
  select email into user_email from auth.users where id = auth.uid();
  insert into public.users (id, username, display_name, email)
  values (auth.uid(), split_part(coalesce(user_email, 'usuario'), '@', 1), split_part(coalesce(user_email, 'usuario'), '@', 1), user_email)
  on conflict (id) do update set email = excluded.email, updated_at = now();
  select su.store_id into store_id from public.store_users su where su.user_id = auth.uid() limit 1;
  if store_id is null then
    select id into store_id from public.stores where cnpj = '12345678000199' limit 1;
    if store_id is null then
      insert into public.stores (name, cnpj, email, phone, address_line, city, state)
      values ('Bromélia Terrários', '12345678000199', 'ola@bromeliaterrarios.com.br', '(11) 99999-8888', 'Rua das Bromélias, 42', 'São Paulo', 'SP')
      returning id into store_id;
    end if;
    insert into public.store_users (store_id, user_id, role) values (store_id, auth.uid(), 'admin')
    on conflict do nothing;
  end if;
  insert into public.store_settings (store_id) values (store_id) on conflict do nothing;
  return store_id;
end $$;
grant execute on function public.ensure_current_user_setup() to authenticated;
