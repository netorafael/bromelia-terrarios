create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(), name varchar(120) not null,
  cnpj varchar(18) unique, email varchar(254) not null, phone varchar(30) not null,
  address_line varchar(200) not null, city varchar(100) not null, state char(2) not null,
  active boolean not null default true, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  username varchar(80) unique not null, display_name varchar(120) not null,
  email varchar(254) unique, active boolean not null default true,
  last_login_at timestamptz, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.store_users (
  store_id uuid references public.stores(id) on delete cascade,
  user_id uuid references public.users(id) on delete cascade,
  role public.user_role not null, created_at timestamptz not null default now(),
  primary key (store_id, user_id)
);
create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(), name varchar(100) not null,
  slug varchar(100) unique not null, product_type public.product_type not null,
  sellable boolean not null default true, sort_order smallint not null default 0,
  active boolean not null default true
);
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id),
  category_id uuid references public.categories(id), type public.product_type not null,
  name varchar(160) not null, sku varchar(60) not null, cost_price numeric(12,2) not null default 0 check (cost_price >= 0),
  sale_price numeric(12,2) check (sale_price is null or sale_price >= 0), cost_unit varchar(20) not null default 'un',
  sellable boolean not null default false, image_url text, active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique (store_id, sku), check (not sellable or sale_price is not null)
);
create table if not exists public.inventory_levels (
  product_id uuid primary key references public.products(id) on delete cascade,
  quantity integer not null default 0 check (quantity >= 0),
  minimum_quantity integer not null default 0 check (minimum_quantity >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.sales (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id),
  sale_number bigint generated by default as identity, status public.sale_status not null default 'pending',
  subtotal numeric(12,2) not null check (subtotal >= 0), discount_percent numeric(5,2) not null default 0 check (discount_percent between 0 and 100),
  discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0), total numeric(12,2) not null check (total >= 0),
  created_by uuid not null references public.users(id), paid_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.sale_items (
  id uuid primary key default gen_random_uuid(), sale_id uuid not null references public.sales(id) on delete cascade,
  product_id uuid not null references public.products(id), product_name_snapshot varchar(160) not null,
  sku_snapshot varchar(60) not null, unit_price numeric(12,2) not null check (unit_price >= 0),
  unit_cost_snapshot numeric(12,2) not null default 0, quantity integer not null check (quantity > 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);
create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(), sale_id uuid not null references public.sales(id) on delete cascade,
  method public.payment_method not null, amount numeric(12,2) not null check (amount > 0),
  status varchar(30) not null default 'pending', external_reference varchar(160),
  paid_at timestamptz, created_at timestamptz not null default now()
);
create table if not exists public.stock_movements (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id),
  product_id uuid not null references public.products(id), type public.stock_movement_type not null,
  quantity_delta integer not null, quantity_before integer not null check (quantity_before >= 0),
  quantity_after integer not null check (quantity_after >= 0), unit_cost numeric(12,2),
  sale_id uuid references public.sales(id), notes text, created_by uuid not null references public.users(id),
  created_at timestamptz not null default now()
);
create table if not exists public.store_settings (
  store_id uuid primary key references public.stores(id) on delete cascade,
  low_stock_alert_enabled boolean not null default true, default_low_stock_quantity integer not null default 5,
  sales_alert_email boolean not null default true, sales_alert_whatsapp boolean not null default true,
  weekly_report_enabled boolean not null default true, weekly_report_weekday smallint not null default 1,
  timezone varchar(50) not null default 'America/Sao_Paulo', updated_at timestamptz not null default now()
);
create table if not exists public.notification_preferences (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references public.users(id) on delete cascade,
  store_id uuid not null references public.stores(id) on delete cascade, event_type varchar(50) not null,
  channel varchar(20) not null, enabled boolean not null default true,
  unique (user_id, store_id, event_type, channel)
);

